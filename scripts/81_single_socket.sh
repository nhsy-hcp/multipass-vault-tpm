#!/bin/bash
# One Vault Agent API proxy on an owner-only Unix socket.
#
# Same shape as one instance of scripts/81_app_proxies.sh: a system user, a
# mode-0600 socket owned by that user, and an agent fixed to one TPM role.
# The agent process stays root so the TPM state directory stays unreadable
# by the workload. Only the socket is theirs.
#
# Vault 2.2.0+ent registers method "tpm" on `vault agent`, not
# `vault proxy`.
set -euo pipefail
STAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${STAGE_DIR}/common.sh"

device="${1:-node01}"
domain="${2:-devices.lab.local}"
app="payments"
role="machine-cli"
secret_path="secret/devices/${device}"
home="/var/lib/lab-${app}"
run_dir="/run/vault-proxy"
conf_dir="/etc/vault-proxy"
state_dir="/var/lib/vault-agent/${app}/tpm"
unit_path="/etc/systemd/system/vault-proxy@.service"
config="${conf_dir}/${app}.hcl"
sock="${run_dir}/${app}.sock"
unit="vault-proxy@${app}"
ca_pem="${LAB_TLS_DIR}/vault-ca.pem"
device_cn="${device}.${domain}"

require_cmd vault systemctl install useradd id stat || die "missing prerequisites"
[[ -f "${ca_pem}" ]] || die "no Vault CA at ${ca_pem} — run 'task vault' first"
[[ -S "${SWTPM_UNIX_SOCK}" ]] || die "no ${SWTPM_UNIX_SOCK} — run 'task tpm' first"
as_lab_user_allow_fail vault read "auth/tpm/role/${role}" >/dev/null 2>&1 \
  || die "auth/tpm/role/${role} missing — create that role before 'task proxy:socket'"

log_step "One workload through an owner-only Unix socket"
log_info "User ${app} will use unix://${sock}."
log_info "Vault Agent attests as ${role} and forces that token on the socket."

systemctl stop vault-proxy-single vault-proxy@payments vault-proxy@analytics \
  >/dev/null 2>&1 || true
if pgrep -f 'vault (agent|proxy) -config=/etc/vault-proxy/' >/dev/null 2>&1; then
  log_detected "a vault agent/proxy outside systemd" "stopping it"
  pkill -f 'vault (agent|proxy) -config=/etc/vault-proxy/' || true
  sleep 0.3
fi

if ! id "${app}" >/dev/null 2>&1; then
  useradd --system --create-home --home-dir "${home}" --shell /usr/sbin/nologin "${app}"
  log_ok "created user ${app}"
else
  log_detected "user ${app}" "leaving the account in place"
fi
install -d -o "${app}" -g "${app}" -m 0700 "${home}"
install -d -m 0755 "${run_dir}" "${conf_dir}" /var/lib/vault-agent
install -d -m 0700 "${state_dir}"

# Unix listener matches templates/vault-proxy.hcl.tpl. The role is machine-cli,
# the one already created for the direct CLI login.
if write_if_changed "${config}" <<EOF
# Generated by scripts/81_single_socket.sh.
# Role ${role}, user ${app}. TPM auto-auth via vault agent.
vault {
  address = "https://127.0.0.1:8200"
  ca_cert = "${ca_pem}"
}

tpm_cert "host_identity" {
  mount_path = "auth/tpm"
  role_name  = "${role}"

  tpm {
    device_path = "${SWTPM_UNIX_SOCK}"
  }

  renew {
    percent_renew_before_expiry = 20
    min_backoff                 = "5s"
    max_backoff                 = "5m"
  }

  csr {
    CN = "${device_cn}"
  }

  destination {
    path  = "${state_dir}"
    umask = "077"
  }
}

auto_auth {
  method "tpm" {
    mount_path = "auth/tpm"
    config = {
      tpm_cert  = "host_identity"
      role_name = "${role}"
    }
  }
}

api_proxy {
  use_auto_auth_token = "force"
}

listener "unix" {
  address      = "${sock}"
  socket_mode  = "600"
  socket_user  = "${app}"
  socket_group = "${app}"
  tls_disable  = true
}
EOF
then
  log_info "Wrote ${config}"
else
  log_detected "unchanged ${config}" "leaving it"
fi

# Same unit as templates/vault-proxy.service.tpl. One instance: ${unit}.
unit_changed=0
if write_if_changed "${unit_path}" <<'EOF'
# Generated by scripts/81_single_socket.sh.
[Unit]
Description=Vault agent API proxy for %i (TPM auto-auth)
After=network-online.target vault-dev.service swtpm-unix-bridge.service
Wants=vault-dev.service swtpm-unix-bridge.service

[Service]
Type=simple
ExecStart=/usr/local/bin/vault agent -config=/etc/vault-proxy/%i.hcl
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
then
  unit_changed=1
  log_info "Wrote ${unit_path}"
fi
(( unit_changed == 0 )) || systemctl daemon-reload

# A previous attest may still hold swtpm's transient contexts, and a failed
# login may have tripped the dictionary-attack lockout.
log_info "Restarting swtpm@device to clear transient TPM contexts"
systemctl restart swtpm@device
wait_for_unit swtpm@device 30 || die "swtpm@device did not recover"
systemctl restart swtpm-unix-bridge
wait_for_unit swtpm-unix-bridge 15 || die "swtpm-unix-bridge did not recover"
as_lab_user tpm2_dictionarylockout -c || true

# Stale blobs make the agent Load() a key the restarted TPM no longer has.
find "${state_dir}" -mindepth 1 -type f -delete 2>/dev/null || true

log_info "Starting ${unit}; certificate acquisition may wait for the EK rate limit."
systemctl enable "${unit}" >/dev/null
systemctl restart "${unit}"

# Up to ~120s. The auth mount rate-limits certificate acquisition per EK, and
# the agent's retry backoff after that limit is about 50s.
for _ in $(seq 1 480); do
  if systemctl is-failed --quiet "${unit}"; then
    break
  fi
  recent="$(journalctl -u "${unit}" -n 30 --no-pager 2>/dev/null || true)"
  if [[ -S "${sock}" ]]; then
    mode="$(stat -c '%a' "${sock}")"
    owner="$(stat -c '%U:%G' "${sock}")"
    if [[ "${mode}" == "600" && "${owner}" == "${app}:${app}" ]] \
      && printf '%s' "${recent}" | grep -q 'authentication successful'; then
      log_ok "${sock} owned by ${owner}, mode ${mode} (TPM auth ok)"
      log_info "As ${app}: VAULT_ADDR=unix://${sock} vault kv get ${secret_path}"
      exit 0
    fi
  fi
  sleep 0.25
done

journalctl -u "${unit}" --no-pager -n 60 >&2 || true
die "${sock} did not come up with TPM authentication"
