#!/bin/bash
# Part 11: one Vault Agent per application, each behind an owner-only socket.
set -euo pipefail
STAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${STAGE_DIR}/common.sh"

# -----------------------------------------------------------------------------
# The TPM proves which machine is asking, never which application: payments-app
# and analytics-app both trust the 'devices' group, so anything that can drive
# this TPM can attest for either role. The boundary between applications has
# to come from the operating system, and this part builds it:
#
#   - a system user per application (payments, analytics);
#   - an agent per application, its role fixed in its own config, forcing its
#     own token on every request (use_auto_auth_token = "force");
#   - each agent listening on a unix socket owned by that application's user,
#     mode 0600 — the only route the application has to Vault;
#   - the agents running as root, so neither application can open the TPM or
#     read the agents' certificate and key blobs.
#
# The last point is a deliberate exception to "artefacts are owned by the lab
# user". Only root can hand a listening socket to another uid, and an agent
# running as the application's own user would give that user the TPM — and
# with it a login as any role the group is trusted for.
#
# Same conventions as Parts 9 and 10: units installed disabled, started here,
# their own attest directories, stopped by an EXIT trap. Reports rather than
# asserts.
# -----------------------------------------------------------------------------

DEVICE="${1:-node01}"

TPM_MOUNT="tpm"
TPM_GROUP="devices"
APPS=(payments analytics)

DEVICE_DIR="${TPM_DIR}/${DEVICE}"
RUN_DIR="/run/vault-proxy"
CONF_DIR="/etc/vault-proxy"
UNIT_PATH="/etc/systemd/system/vault-proxy@.service"
VAULT_EXE="/usr/bin/vault"

# Attest directories sit under TPM_DIR, one level down like every device's, so
# 'task config' clears their certificates when a fresh mount brings a new CA
# and 'task reset' removes them with the rest of the lab state.
app_state() { printf '%s/app-%s' "${TPM_DIR}" "$1"; }
app_sock()  { printf '%s/%s.sock' "${RUN_DIR}" "$1"; }

log_step "Part 11: per-application agents on owner-only sockets (${DEVICE})"

require_cmd jq systemctl runuser useradd stat || die "missing prerequisites"
[[ -x "${VAULT_EXE}" ]] || die "${VAULT_EXE} is missing — run 'task provision' first"
[[ -S "${TPM_SOCK}" ]] || die "no device TPM at ${TPM_SOCK} — run 'task tpm' first"
[[ -s "${STATE_DIR}/config.json" ]] || die "no lab configuration — run 'task config' first"
wait_for "Vault to be unsealed" 60 as_lab_user vault status \
  || die "Vault is not answering — inspect with: journalctl -u vault-dev --no-pager -n 50"

# --- 11.1 the gate -----------------------------------------------------------
log_step "11.1 The gate: an admitted TPM and one role per application"

[[ -s "${DEVICE_DIR}/tpm_id" ]] \
  || die "no TPM ID at ${DEVICE_DIR}/tpm_id — run 'task enrol' first"
tpm_id="$(< "${DEVICE_DIR}/tpm_id")"
as_lab_user vault read -format=json "identity/tpmgroup/name/${TPM_GROUP}" \
  | jq -e --arg id "${tpm_id}" '.data.member_tpm_ids // [] | index($id)' >/dev/null 2>&1 \
  || die "${DEVICE} is not a member of the '${TPM_GROUP}' group — run 'task config && task enrol'"
for app in "${APPS[@]}"; do
  as_lab_user vault read "auth/${TPM_MOUNT}/role/${app}-app" >/dev/null 2>&1 \
    || die "auth/${TPM_MOUNT}/role/${app}-app is missing — run 'task config'"
done
log_ok "${tpm_id} is in '${TPM_GROUP}'; $(printf '%s-app ' "${APPS[@]}")both trust it"

# --- 11.2 users, configs, unit -----------------------------------------------
log_step "11.2 A user, a config and an agent per application"

install -d -m 0755 "${RUN_DIR}" "${CONF_DIR}"

for app in "${APPS[@]}"; do
  if id -u "${app}" >/dev/null 2>&1; then
    log_detected "user ${app}" "keeping it"
  else
    show_cmd useradd --system --create-home --home-dir "/var/lib/lab-${app}" \
      --shell /usr/sbin/nologin "${app}"
    useradd --system --create-home --home-dir "/var/lib/lab-${app}" \
      --shell /usr/sbin/nologin "${app}"
  fi
  install -d -m 0700 "$(app_state "${app}")"

  # Authoritative copy; templates/vault-proxy.hcl.tpl is the reference.
  if write_if_changed "${CONF_DIR}/${app}.hcl" <<EOF
# Vault Agent API proxy for ${app}. Generated by scripts/82_app_proxies.sh.
# The role is fixed here: the application cannot ask for a different one.

vault {
  address = "https://127.0.0.1:8200"
  ca_cert = "${TLS_DIR}/vault-ca.pem"
}

tpm_cert "${app}" {
  role_name  = "${app}-app"
  mount_path = "auth/${TPM_MOUNT}"

  tpm {
    device_path = "${TPM_SOCK}"
  }

  destination {
    path = "$(app_state "${app}")"
  }

  renew {
    min_validity_percentage = 50
  }
}

auto_auth {
  method {
    type       = "tpm"
    mount_path = "auth/${TPM_MOUNT}"

    # One attestation per EK every ten seconds: the second agent waits its turn.
    min_backoff = "10s"
    max_backoff = "2m"

    config = {
      tpm_cert = "${app}"
    }
  }
}

api_proxy {
  use_auto_auth_token = "force"
}

listener "unix" {
  address      = "$(app_sock "${app}")"
  socket_mode  = "600"
  socket_user  = "${app}"
  socket_group = "${app}"
  tls_disable  = true
}
EOF
  then
    log_info "Wrote ${CONF_DIR}/${app}.hcl"
  else
    log_detected "unchanged ${CONF_DIR}/${app}.hcl" "no rewrite needed"
  fi
  chmod 0600 "${CONF_DIR}/${app}.hcl"
done
log_detail "$(sed 's/^/  /' "${CONF_DIR}/${APPS[0]}.hcl")"

# Authoritative copy; templates/vault-proxy.service.tpl is the reference. Runs
# as root — see the header for why.
unit_changed=0
if write_if_changed "${UNIT_PATH}" <<EOF
# Vault Agent API proxy (TPM auto-auth) for one application, %i.
# Generated by scripts/82_app_proxies.sh.
[Unit]
Description=Vault Agent API proxy for %i (TPM auto-auth, role %i-app)
Documentation=https://developer.hashicorp.com/vault/docs/agent-and-proxy/agent/apiproxy
After=network-online.target vault-dev.service swtpm@device.service
Wants=network-online.target
ConditionPathExists=${DEVICE_DIR}/tpm_id

[Service]
Type=simple
Environment=VAULT_TOKEN=
ExecStart=${VAULT_EXE} agent -config=${CONF_DIR}/%i.hcl
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
then
  unit_changed=1
  log_info "Wrote ${UNIT_PATH}"
else
  log_detected "unchanged ${UNIT_PATH}" "no systemd reload needed"
fi
(( unit_changed == 0 )) || systemctl daemon-reload

# --- 11.3 start, one at a time -----------------------------------------------
log_step "11.3 Start the agents, one at a time"

units=()
for app in "${APPS[@]}"; do units+=("vault-proxy@${app}"); done
systemctl disable "${units[@]}" >/dev/null 2>&1 || true
systemctl stop "${units[@]}" >/dev/null 2>&1 || true

cleanup() {
  systemctl stop "${units[@]}" >/dev/null 2>&1 || true
  flush_tpm_contexts "${TPM_SOCK}"
}
trap cleanup EXIT

flush_tpm_contexts "${TPM_SOCK}"

app_ready() {
  local app="$1" since="$2" sock
  sock="$(app_sock "${app}")"
  [[ -S "${sock}" ]] \
    && [[ "$(stat -c '%U:%G %a' "${sock}")" == "${app}:${app} 600" ]] \
    && journalctl -u "vault-proxy@${app}" --no-pager --since "${since}" \
      | grep -q 'authentication successful'
}

# Sequential, so the two attestations do not compete for the TPM's three
# transient slots, and the second one meets the per-EK rate limit at most once.
#
# Each agent attests as soon as it starts, and Vault allows one attestation per
# EK every ten seconds. A refused agent schedules its own retry about 45s out,
# so waiting the 12s tpm_attest uses is the quicker path.
for app in "${APPS[@]}"; do
  log_detected "Vault's per-EK attestation rate limit" "waiting 12s before starting ${app}'s agent"
  sleep 12
  since="$(date '+%Y-%m-%d %H:%M:%S')"
  show_cmd systemctl start "vault-proxy@${app}"
  systemctl start "vault-proxy@${app}"
  wait_for_unit "vault-proxy@${app}" 30 \
    || die "vault-proxy@${app} did not stay active — inspect with: journalctl -u vault-proxy@${app} --no-pager -n 50"
  if wait_for "${app}'s agent to attest and log in" 120 app_ready "${app}" "${since}"; then
    log_detail "  $(stat -c '%n  %U:%G  %a' "$(app_sock "${app}")")"
  else
    log_warn "${app}'s agent has not authenticated — the checks below will show why"
  fi
done

# --- 11.4 the boundary -------------------------------------------------------
log_step "11.4 The boundary, from each application's side"

# Each check runs as the application's own user, with no lab environment: that
# file carries the dev root token. Shown, then run, from the same argv.
as_app() {
  local user="$1" sock="$2"; shift 2
  local argv=(runuser -u "${user}" -- env -u VAULT_TOKEN "VAULT_ADDR=unix://${sock}" "$@")
  show_cmd "${argv[@]}"
  "${argv[@]}" 2>&1
}

pay_sock="$(app_sock payments)"
ana_sock="$(app_sock analytics)"

log_info "1. payments, through its own socket, reads its own secret."
out="$(as_app payments "${pay_sock}" vault kv get -field=message secret/payments/app)" || true
report_expect "payments settlement batch" "${out}"

log_info ""
log_info "2. The same socket is refused the analytics secret (policy payments-read)."
out="$(as_app payments "${pay_sock}" vault kv get -field=message secret/analytics/app)" || true
report_expect "permission denied" "$(printf '%s' "${out}" | grep -io -m1 'permission denied' || printf '%s' "${out}")"

log_info ""
log_info "3. The dev root token on that request changes nothing: the agent forces its own."
show_cmd runuser -u payments -- env 'VAULT_TOKEN=<root>' "VAULT_ADDR=unix://${pay_sock}" \
  vault kv get -field=message secret/analytics/app
out="$(runuser -u payments -- env VAULT_TOKEN=root "VAULT_ADDR=unix://${pay_sock}" \
  vault kv get -field=message secret/analytics/app 2>&1)" || true
report_expect "permission denied" "$(printf '%s' "${out}" | grep -io -m1 'permission denied' || printf '%s' "${out}")"

log_info ""
log_info "4. analytics cannot even open the payments socket."
out="$(as_app analytics "${pay_sock}" vault kv get -field=message secret/payments/app)" || true
report_expect "dial unix ${pay_sock}: connect: permission denied" \
              "$(printf '%s' "${out}" | grep -o -m1 'dial unix.*' || printf '%s' "${out}")"

log_info ""
log_info "5. analytics, through its own socket, reads its own secret."
out="$(as_app analytics "${ana_sock}" vault kv get -field=message secret/analytics/app)" || true
report_expect "analytics risk model" "${out}"

log_info ""
log_info "6. Neither application can reach the TPM, or the agents' certificate and key blobs."
for app in "${APPS[@]}"; do
  tpm_rc=0;   runuser -u "${app}" -- test -w "${TPM_SOCK}" || tpm_rc=$?
  state_rc=0; runuser -u "${app}" -- ls "$(app_state "${app}")" >/dev/null 2>&1 || state_rc=$?
  report_expect "${app}: TPM socket refused, own agent's state refused" \
    "${app}: TPM socket $( (( tpm_rc != 0 )) && echo refused || echo REACHABLE), state $( (( state_rc != 0 )) && echo refused || echo READABLE)"
done
log_detail "  Without this, an application could drive the TPM itself and attest for"
log_detail "  the other application's role — both roles trust the same group."

# --- close -------------------------------------------------------------------
log_info ''
log_ok "each application reaches Vault only through its own agent, as one fixed role"
log_info ""
log_info "One TPM, one enrolment, two identities in Vault. The TPM anchors the"
log_info "machine; the OS — users, socket modes, a root-owned TPM — separates the"
log_info "applications on it."
log_detail ""
log_detail "Both units are stopped and left disabled on the way out. To run one by hand:"
log_detail "  multipass exec $(hostname) -- sudo systemctl start vault-proxy@payments"
log_detail "  task logs:proxy"
