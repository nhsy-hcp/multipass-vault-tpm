#!/bin/bash
# Part 10: one workload, one localhost Vault proxy, no token in the workload.
set -euo pipefail
STAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${STAGE_DIR}/common.sh"

# -----------------------------------------------------------------------------
# Part 9 left the token in a sink file, which the workload must read and
# present. This part removes even that: the agent's api_proxy forwards plain
# Vault requests and forces its own TPM-authenticated token onto every one
# (use_auto_auth_token = "force"). The workload points VAULT_ADDR at
# http://127.0.0.1:8100 and never holds, renews or even sees a token.
#
# This is token automation, not isolation. Any local process can reach a TCP
# listener on loopback and gets the payments-app token's privileges; Part 11
# is the variant that draws a boundary between applications.
#
# Same conventions as Part 9: the unit is installed disabled and started here,
# the agent attests into its own directory, and an EXIT trap stops it again so
# the device TPM is left as the other parts expect it. Reports rather than
# asserts.
# -----------------------------------------------------------------------------

DEVICE="${1:-node01}"

TPM_MOUNT="tpm"
TPM_GROUP="devices"
APP="payments"
ROLE="${APP}-app"
LISTEN="127.0.0.1:8100"
PROXY_ADDR="http://${LISTEN}"

DEVICE_DIR="${TPM_DIR}/${DEVICE}"
PROXY_DIR="${VM_DIR}/proxy"
PROXY_STATE="${TPM_DIR}/proxy"
PROXY_HCL="${PROXY_DIR}/proxy.hcl"
UNIT="vault-proxy-single"
UNIT_PATH="/etc/systemd/system/${UNIT}.service"
VAULT_EXE="/usr/bin/vault"

log_step "Part 10: a localhost Vault proxy — the workload holds no token (${DEVICE})"

require_cmd jq systemctl ss || die "missing prerequisites"
[[ -x "${VAULT_EXE}" ]] || die "${VAULT_EXE} is missing — run 'task provision' first"
[[ -S "${TPM_SOCK}" ]] || die "no device TPM at ${TPM_SOCK} — run 'task tpm' first"
[[ -s "${STATE_DIR}/config.json" ]] || die "no lab configuration — run 'task config' first"
wait_for "Vault to be unsealed" 60 as_lab_user vault status \
  || die "Vault is not answering — inspect with: journalctl -u vault-dev --no-pager -n 50"

# --- 10.1 the gate -----------------------------------------------------------
# Same gate as Part 9, plus the role this part needs: the registry and the role
# are both in memory, so a restarted dev-mode Vault fails here, not in the agent.
log_step "10.1 The gate: an admitted TPM and the '${ROLE}' role"

[[ -s "${DEVICE_DIR}/tpm_id" ]] \
  || die "no TPM ID at ${DEVICE_DIR}/tpm_id — run 'task enrol' first"
tpm_id="$(< "${DEVICE_DIR}/tpm_id")"
as_lab_user vault read -format=json "identity/tpmgroup/name/${TPM_GROUP}" \
  | jq -e --arg id "${tpm_id}" '.data.member_tpm_ids // [] | index($id)' >/dev/null 2>&1 \
  || die "${DEVICE} is not a member of the '${TPM_GROUP}' group — run 'task config && task enrol'"
as_lab_user vault read "auth/${TPM_MOUNT}/role/${ROLE}" >/dev/null 2>&1 \
  || die "auth/${TPM_MOUNT}/role/${ROLE} is missing — run 'task config'"
log_ok "${tpm_id} is in '${TPM_GROUP}', and '${ROLE}' trusts that group"

# --- 10.2 the configuration --------------------------------------------------
log_step "10.2 The proxy configuration"

lab_mkdir "${PROXY_DIR}" "${PROXY_STATE}"

# Authoritative copy of the config. templates/vault-proxy-single.hcl.tpl is the
# readable reference of exactly this content and must be kept in sync.
#
# `vault agent`, not `vault proxy`: in 2.2.0 the tpm auto-auth method exists
# only in the agent ("unknown auto-auth method type tpm" from the proxy). The
# agent's api_proxy stanza gives the same listener behaviour.
if write_if_changed "${PROXY_HCL}" <<EOF
# Vault Agent API proxy for one workload. Generated by scripts/81_proxy.sh.

vault {
  address = "https://127.0.0.1:8200"
  ca_cert = "${TLS_DIR}/vault-ca.pem"
}

tpm_cert "${APP}" {
  role_name  = "${ROLE}"
  mount_path = "auth/${TPM_MOUNT}"

  tpm {
    device_path = "${TPM_SOCK}"
  }

  destination {
    path = "${PROXY_STATE}"
  }

  renew {
    min_validity_percentage = 50
  }
}

auto_auth {
  method {
    type       = "tpm"
    mount_path = "auth/${TPM_MOUNT}"

    # Vault rate-limits attestation to one per EK every ten seconds, and Part 9
    # attested moments ago.
    min_backoff = "10s"
    max_backoff = "2m"

    config = {
      tpm_cert = "${APP}"
    }
  }
}

# Every request through the listener carries the agent's token, whatever the
# caller sent — including no token, and including root.
api_proxy {
  use_auto_auth_token = "force"
}

listener "tcp" {
  address     = "${LISTEN}"
  tls_disable = true
}
EOF
then
  log_info "Wrote ${PROXY_HCL}"
else
  log_detected "unchanged ${PROXY_HCL}" "no rewrite needed"
fi
chown "${VM_USER}:${VM_USER}" "${PROXY_HCL}"
chmod 0640 "${PROXY_HCL}"
log_detail "$(sed 's/^/  /' "${PROXY_HCL}")"

# --- 10.3 the unit -----------------------------------------------------------
log_step "10.3 The unit: installed disabled, started only now"

# Authoritative copy of the unit; templates/vault-proxy-single.service.tpl is
# its reference. Environment=VAULT_TOKEN= for the same reason as Part 9: the
# daemon starts with no credential.
unit_changed=0
if write_if_changed "${UNIT_PATH}" <<EOF
# Vault Agent API proxy (TPM auto-auth) for one workload.
# Generated by scripts/81_proxy.sh.
[Unit]
Description=Vault Agent API proxy on ${LISTEN} (TPM auto-auth, role ${ROLE})
Documentation=https://developer.hashicorp.com/vault/docs/agent-and-proxy/agent/apiproxy
After=network-online.target vault-dev.service swtpm@device.service
Wants=network-online.target
ConditionPathExists=${DEVICE_DIR}/tpm_id

[Service]
Type=simple
User=${VM_USER}
Group=${VM_USER}
WorkingDirectory=${PROXY_DIR}
Environment=VAULT_TOKEN=
ExecStart=${VAULT_EXE} agent -config=${PROXY_HCL}
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
then
  unit_changed=1
  log_info "Wrote ${UNIT_PATH}"
else
  log_detected "unchanged ${UNIT_PATH}" "no systemd reload needed"
fi
(( unit_changed == 0 )) || systemctl daemon-reload

# Disabled for the reason Part 9 gives: dev-mode Vault forgets the mount on a
# restart, so an enabled proxy would start at boot ahead of enrolment.
systemctl disable "${UNIT}" >/dev/null 2>&1 || true
systemctl stop "${UNIT}" >/dev/null 2>&1 || true

cleanup() {
  systemctl stop "${UNIT}" >/dev/null 2>&1 || true
  flush_tpm_contexts "${TPM_SOCK}"
}
trap cleanup EXIT

flush_tpm_contexts "${TPM_SOCK}"

# The agent attests the moment it starts, and Vault allows one attestation per
# EK every ten seconds — Part 9 may have used it. A refused agent retries about
# 45s later, so waiting the 12s tpm_attest uses is the quicker path.
log_detected "Vault's per-EK attestation rate limit" "waiting 12s before starting the proxy"
sleep 12
since="$(date '+%Y-%m-%d %H:%M:%S')"
show_cmd systemctl start "${UNIT}"
systemctl start "${UNIT}"
wait_for_unit "${UNIT}" 30 \
  || die "${UNIT} did not stay active — inspect with: journalctl -u ${UNIT} --no-pager -n 50"

proxy_ready() {
  ss -ltn | grep -qF "${LISTEN}" \
    && journalctl -u "${UNIT}" --no-pager --since "${since}" \
      | grep -q 'authentication successful'
}
wait_for "the proxy to attest and log in" 120 proxy_ready \
  || log_warn "the proxy has not authenticated — the reads below will show why"

# --- 10.4 the workload -------------------------------------------------------
# The workload runs as the lab user but overrides VAULT_ADDR, and carries the
# placeholder token: the transcript shows it holds no credential of its own.
log_step "10.4 The workload reads its secret through the proxy"

rc=0
out="$(vault_run_allow_fail env "VAULT_ADDR=${PROXY_ADDR}" "VAULT_TOKEN=${NO_TOKEN}" \
  vault kv get -field=message "secret/${APP}/app" 2>&1)" || rc=$?
report_expect "payments settlement batch" \
  "$( (( rc == 0 )) && printf '%s' "${out}" || printf 'read failed (rc=%s): %s' "${rc}" "${out}")"

# --- 10.5 the caller's token is ignored --------------------------------------
log_step "10.5 A caller-supplied root token does not widen the proxy"
log_detail "  The agent replaces whatever token arrives with its own payments-app"
log_detail "  token, so even the dev root token reaches Vault as payments-read."

# Labelled rather than shown: fmt_cmd redacts tokens, and which token is on the
# request is the point.
show_cmd env "VAULT_ADDR=${PROXY_ADDR}" 'VAULT_TOKEN=<root>' \
  vault kv get -field=message secret/analytics/app
rc=0
out="$(as_lab_user_allow_fail env "VAULT_ADDR=${PROXY_ADDR}" VAULT_TOKEN=root \
  vault kv get -field=message secret/analytics/app 2>&1)" || rc=$?
if (( rc != 0 )) && printf '%s' "${out}" | grep -qi 'permission denied'; then
  report_expect "permission denied (the agent forced its own token)" \
                "permission denied (vault exit ${rc})"
else
  report_expect "permission denied (the agent forced its own token)" \
                "rc=${rc}: ${out}"
fi

# --- close -------------------------------------------------------------------
log_info ''
log_ok "the workload used a plain URL; the agent attested, logged in and owns the token"
log_info ""
log_info "Anything on this host that can reach ${LISTEN} gets the same payments-app"
log_info "privileges — the listener is a convenience, not a boundary. Part 11 gives"
log_info "each application its own agent, role and owner-only socket."
log_detail ""
log_detail "The unit is stopped and left disabled on the way out. To run it by hand:"
log_detail "  multipass exec $(hostname) -- sudo systemctl start ${UNIT}"
log_detail "  task logs:proxy"
