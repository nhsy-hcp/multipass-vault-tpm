#!/bin/bash
# Part 9: Vault Agent does the device's work with nobody watching.
set -euo pipefail
STAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${STAGE_DIR}/common.sh"

# -----------------------------------------------------------------------------
# Parts 6 and 7 are an operator typing commands. This part hands both to a
# daemon and changes nothing about the trust model.
#
# The agent config has two halves, and the split is the lesson:
#
#   tpm_cert "<device>" { ... }   gets and keeps the certificate — it attests on
#                                first run, persists the blobs, and schedules
#                                its own renewal inside the certificate's life
#   auto_auth { method "tpm" }    uses that certificate to log in, and writes
#                                the resulting token to a sink
#
# So the agent performs the device's half of Part 6 and all of Part 7 by
# itself. What it cannot do is register its own endorsement key: admitting a
# TPM to the group the role trusts still needs the orchestrator's scoped token.
# Automation replaces the device, never the party that decides what to trust.
#
# Like the Part 8 scripts this one reports rather than asserts, and exits 0 even
# when an expectation is missed. It stops the agent on the way out, so the
# device TPM is left as Parts 7 and 8 expect it.
# -----------------------------------------------------------------------------

DEVICE="${1:-node01}"

TPM_MOUNT="tpm"
TPM_ROLE="devices"
TPM_GROUP="devices"

DEVICE_DIR="${TPM_DIR}/${DEVICE}"
AGENT_DIR="${VM_DIR}/agent"
AGENT_STATE="${TPM_DIR}/agent"
AGENT_HCL="${AGENT_DIR}/agent.hcl"
TPL_SRC="${AGENT_DIR}/message.tpl"
TPL_OUT="${AGENT_DIR}/message.txt"
SINK="${AGENT_DIR}/token"
UNIT_PATH="/etc/systemd/system/vault-agent.service"
VAULT_EXE="/usr/bin/vault"

log_step "Part 9: Vault Agent — attestation and login with no operator (${DEVICE})"

require_cmd jq systemctl || die "missing prerequisites"
[[ -x "${VAULT_EXE}" ]] || die "${VAULT_EXE} is missing — run 'task provision' first"
[[ -f "${VM_DIR}/env.sh" ]] || die "no ${VM_DIR}/env.sh — run 'task provision' first"
[[ -S "${TPM_SOCK}" ]] || die "no device TPM at ${TPM_SOCK} — run 'task tpm' first"
[[ -s "${STATE_DIR}/config.json" ]] || die "no lab configuration — run 'task config' first"
wait_for "Vault to be unsealed" 60 as_lab_user vault status \
  || die "Vault is not answering — inspect with: journalctl -u vault-dev --no-pager -n 50"

# --- 9.1 the gate ------------------------------------------------------------
# The agent issues its own certificate, so the device's certificate and its
# expiry are irrelevant here. What must hold is that the orchestrator has
# registered this EK and admitted it to the group the role trusts — and that is
# also the check which catches a restarted dev-mode Vault, because the registry
# is in memory and does not survive.
log_step "9.1 The gate: has the orchestrator admitted this TPM?"

[[ -s "${DEVICE_DIR}/tpm_id" ]] \
  || die "no TPM ID at ${DEVICE_DIR}/tpm_id — run 'task enrol' first"
tpm_id="$(< "${DEVICE_DIR}/tpm_id")"

as_lab_user vault read "identity/tpm/name/${DEVICE}" >/dev/null 2>&1 \
  || die "the EK for ${DEVICE} is not registered in identity/tpm — Vault was probably restarted; run 'task config && task enrol'"

as_lab_user vault read -format=json "identity/tpmgroup/name/${TPM_GROUP}" \
  | jq -e --arg id "${tpm_id}" '.data.member_tpm_ids // [] | index($id)' >/dev/null 2>&1 \
  || die "${DEVICE} is not a member of the '${TPM_GROUP}' group — run 'task enrol'"

log_ok "${tpm_id} is registered and in the '${TPM_GROUP}' group"
log_detail "  The agent could not have done either of those for itself."

# --- 9.2 the configuration ---------------------------------------------------
log_step "9.2 The agent configuration"

lab_mkdir "${AGENT_DIR}" "${AGENT_STATE}"

# Authoritative copy of the config. templates/vault-agent.hcl.tpl is the
# readable reference of exactly this content and must be kept in sync —
# templates live on the host and are never transferred into the VM.
#
# role_name belongs to the tpm_cert block; keep it there only. Unknown keys in
# these blocks are dropped in silence, so a typo here costs a debugging
# session, and an empty tpm_cert block segfaults the agent.
if write_if_changed "${AGENT_HCL}" <<EOF
# Vault Agent for the TPM auth lab. Generated by scripts/80_agent.sh.

vault {
  address = "https://127.0.0.1:8200"
  ca_cert = "${TLS_DIR}/vault-ca.pem"
}

# Gets and keeps the certificate: attests on first run, persists the blobs
# under destination.path, and schedules renewal inside the certificate's life.
tpm_cert "${DEVICE}" {
  role_name  = "${TPM_ROLE}"
  mount_path = "auth/${TPM_MOUNT}"

  # On real hardware this is /dev/tpmrm0 and nothing else changes.
  tpm {
    device_path = "${TPM_SOCK}"
  }

  destination {
    path = "${AGENT_STATE}"
  }

  renew {
    min_validity_percentage = 50
  }
}

# Uses that certificate to log in, and writes the token to a sink.
auto_auth {
  method {
    type       = "tpm"
    mount_path = "auth/${TPM_MOUNT}"

    # Vault rate-limits attestation to one per EK every ten seconds.
    min_backoff = "10s"
    max_backoff = "2m"

    config = {
      tpm_cert = "${DEVICE}"
    }
  }

  sink {
    type = "file"
    config = {
      path = "${SINK}"
    }
  }
}

template {
  source      = "${TPL_SRC}"
  destination = "${TPL_OUT}"
  perms       = "0640"
}
EOF
then
  log_info "Wrote ${AGENT_HCL}"
else
  log_detected "unchanged ${AGENT_HCL}" "no rewrite needed"
fi
chown "${VM_USER}:${VM_USER}" "${AGENT_HCL}"
chmod 0640 "${AGENT_HCL}"

# The KV v2 data path, which is what the device-read policy grants.
if write_if_changed "${TPL_SRC}" <<EOF
{{ with secret "secret/data/devices/${DEVICE}" }}{{ .Data.data.message }}{{ end }}
EOF
then
  log_info "Wrote ${TPL_SRC}"
else
  log_detected "unchanged ${TPL_SRC}" "no rewrite needed"
fi
chown "${VM_USER}:${VM_USER}" "${TPL_SRC}"

log_info ""
log_detail "$(sed 's/^/  /' "${AGENT_HCL}")"
log_info ""
log_detail "  The template it renders:"
log_detail "$(sed 's/^/    /' "${TPL_SRC}")"

# --- 9.3 the unit ------------------------------------------------------------
log_step "9.3 The unit: installed disabled, started only now"

# Authoritative copy of the unit. templates/vault-agent.service.tpl is the
# readable reference of exactly this content and must be kept in sync.
#
# Environment=VAULT_TOKEN= is load-bearing. ~/lab/env.sh exports
# VAULT_TOKEN=root, and the agent must not inherit it: the whole claim of this
# part is that the daemon starts with no credential at all.
unit_changed=0
if write_if_changed "${UNIT_PATH}" <<EOF
# Vault Agent (TPM auto-auth) for the TPM auth lab.
# Generated by scripts/80_agent.sh.
[Unit]
Description=Vault Agent (TPM auto-auth) for the TPM auth lab
Documentation=https://developer.hashicorp.com/vault/docs/agent-and-proxy/agent
After=network-online.target vault-dev.service swtpm@device.service
Wants=network-online.target
# Enrolment writes this. The agent issues its own certificate but cannot
# register its own EK, so it is useless until the orchestrator has run.
ConditionPathExists=${DEVICE_DIR}/tpm_id

[Service]
Type=simple
User=${VM_USER}
Group=${VM_USER}
WorkingDirectory=${AGENT_DIR}
Environment=VAULT_TOKEN=
ExecStart=${VAULT_EXE} agent -config=${AGENT_HCL}
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
then
  unit_changed=1
  log_info "Wrote ${UNIT_PATH}"
else
  log_detected "unchanged ${UNIT_PATH}" "no systemd reload needed"
fi

if (( unit_changed == 1 )); then
  log_info "Reloading systemd (unit changed)..."
  systemctl daemon-reload
fi

# Deliberately never 'enable --now', unlike every other unit in this lab. Vault
# dev mode is in-memory: a reboot brings back a Vault with no tpm auth mount, no
# CA and no identity/tpm registry, so an enabled agent would start ahead of
# 'task config && task enrol', fail, and retry on a backoff indefinitely.
# swtpm@* and vault-dev are enabled because they hold state; the agent consumes
# state that does not survive.
systemctl disable vault-agent >/dev/null 2>&1 || true
report_expect "disabled (it must not start at boot, ahead of enrolment)" \
              "$(systemctl is-enabled vault-agent 2>&1 || true)"

# Stop any agent left by an earlier run so the journal below is this run's.
systemctl stop vault-agent >/dev/null 2>&1 || true

# Armed before the start: the unit holds the device TPM, so a run that dies
# here must not leave the agent running underneath Parts 7 and 8.
cleanup() {
  systemctl stop vault-agent >/dev/null 2>&1 || true
  rm -f "${SINK}" "${TPL_OUT}"
  flush_tpm_contexts "${TPM_SOCK}"
}
trap cleanup EXIT

# A raw socket has no resource manager: clear anything an interrupted earlier
# run left loaded, so the agent starts with every transient slot free.
flush_tpm_contexts "${TPM_SOCK}"

since="$(date '+%Y-%m-%d %H:%M:%S')"
show_cmd systemctl start vault-agent
systemctl start vault-agent

if ! wait_for_unit vault-agent 30; then
  log_detail "$(journalctl -u vault-agent --no-pager -n 20 | sed 's/^/    /')"
  die "vault-agent did not stay active — inspect with: journalctl -u vault-agent --no-pager -n 50"
fi


# --- 9.4 what it did unattended ----------------------------------------------
log_step "9.4 What the agent did, with nobody watching"

wait_for "the agent's token sink at ${SINK}" 90 test -s "${SINK}" \
  || log_warn "no token reached the sink — the journal below is the place to look"

log_detail "$(journalctl -u vault-agent --no-pager --since "${since}" \
  | grep -E 'tpmattest|auth\.handler|renewal|rendered|sink' \
  | sed -E 's/^.*(agent[.:])/\1/; s/^/    /' | head -14)"

log_info ""
log_info "Material the agent attested for itself, in its own directory:"
log_detail "$(ls -l "${AGENT_STATE}" | sed 's/^/  /')"
log_detail "  Its own, not ${DEVICE_DIR} — the agent attests, and pointing it at the"
log_detail "  device's directory would reissue over what Parts 7 and 8 depend on."

renewal="$(journalctl -u vault-agent --no-pager --since "${since}" \
  | grep -o 'renewal_time="[^"]*"' | head -1 || true)"
[[ -n "${renewal}" ]] && log_detail "  Renewal already scheduled: ${renewal}"

# --- 9.5 the token is the same identity --------------------------------------
log_step "9.5 The token: the same TPM, the same role, no operator"

agent_token="$(cat "${SINK}" 2>/dev/null || true)"
if [[ -z "${agent_token}" ]]; then
  report_expect "a token in ${SINK}" "the sink is empty — see the journal above"
else
  # Labelled rather than redacted: which identity is on the wire is the point.
  show_cmd env 'VAULT_TOKEN=<agent-sink>' vault token lookup -format=json
  lookup="$(as_lab_user_allow_fail env "VAULT_TOKEN=${agent_token}" \
    vault token lookup -format=json 2>&1)" || true

  if printf '%s' "${lookup}" | jq -e . >/dev/null 2>&1; then
    display_name="$(printf '%s' "${lookup}" | jq -r '.data.display_name // "(none)"')"
    policies="$(printf '%s' "${lookup}" | jq -r '(.data.policies // []) | join(", ")')"
    ttl="$(printf '%s' "${lookup}" | jq -r '.data.ttl // 0')"
    meta_tpm="$(printf '%s' "${lookup}" | jq -r '.data.meta.tpm_id // "(none)"')"
    meta_cn="$(printf '%s' "${lookup}" | jq -r '.data.meta.common_name // "(none)"')"

    report_expect "display_name tpm-tpm-devices, policies including device-read" \
                  "display_name ${display_name}, policies ${policies}, ttl ${ttl}s"
    report_expect "tpm_id ${tpm_id} — the TPM ID Part 6 recorded" \
                  "tpm_id ${meta_tpm}"
    if [[ "${meta_tpm}" == "${tpm_id}" ]]; then
      log_ok "the daemon authenticated as the same silicon the operator did in Part 7"
    else
      log_warn "the agent's token names a different TPM than ${DEVICE}"
    fi
    log_detail "  common_name ${meta_cn} — the agent chose this itself; nothing checks it"

    # The whole record, for the operator who wants to see it rather than take
    # four fields on trust. 'id' is the live token and is redacted: this runs in
    # a demo that gets recorded, and the value is usable for its full TTL. The
    # accessor is not a credential and stays, because it is what an audit log
    # names. fmt_cmd redacts tokens in commands; this is the output.
    log_info ""
    log_detail "  The whole token, as Vault sees it:"
    show_cmd env 'VAULT_TOKEN=<agent-sink>' vault token lookup
    log_detail "$(as_lab_user_allow_fail env "VAULT_TOKEN=${agent_token}" \
      vault token lookup 2>&1 \
      | sed -E 's/^(id[[:space:]]+).*/\1<redacted — a live token, and this is a demo>/' \
      | sed 's/^/    /')"
    log_detail "  entity_id is the device's own identity in Vault: one entity alias per"
    log_detail "  TPM, which is what gives per-device attribution in the audit log."
  else
    report_expect "a usable token" "lookup failed: $(printf '%s\n' "${lookup}" | grep -m1 . || printf '(no output)')"
  fi
fi

# --- 9.6 the rendered secret -------------------------------------------------
log_step "9.6 The secret on disk, put there by nobody"

if [[ -s "${TPL_OUT}" ]]; then
  report_expect "hello from vault, attested by TPM key" "$(cat "${TPL_OUT}")"
else
  report_expect "hello from vault, attested by TPM key" "nothing rendered at ${TPL_OUT}"
fi

log_info ""
log_info "Everything the agent leaves on this disk:"
log_detail "$(ls -l "${AGENT_DIR}" | sed 's/^/  /')"
log_detail "  A token it renews and that revocation kills (Part 8.5), a rendered"
log_detail "  secret, its own config — and no private key, here or in ${AGENT_STATE}."

# --- close -------------------------------------------------------------------
log_info ''
log_ok "the device's half of enrolment and all of login, unattended"
log_info ""
log_info "The agent attested, was issued a certificate, logged in over mTLS with a key"
log_info "that cannot leave the TPM, and rendered a secret — with no operator and no"
log_info "token to start from. It could not have registered its own endorsement key:"
log_info "that still belongs to the orchestrator, which is the trust model surviving"
log_info "automation rather than being bypassed by it."
log_info ""
log_detail "The unit is stopped and left disabled on the way out, so the device TPM is"
log_detail "left as Parts 7 and 8 expect it. To watch it run, both from the host — the"
log_detail "unit is in the VM, the task is not:"
log_detail "  multipass exec $(hostname) -- sudo systemctl start vault-agent"
log_detail "  task logs:agent"
log_detail ""
log_detail "If a run is interrupted and a TPM command then reports \"out of memory for"
log_detail "object contexts\", a key was left loaded on the raw socket. Clear it with:"
log_detail "  task tpm:flush"
