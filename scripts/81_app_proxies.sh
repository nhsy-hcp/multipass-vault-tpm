#!/bin/bash
# Workflow 3: one Vault Agent API proxy per application, each on a Unix socket
# that only that application's user can open.
#
# Vault 2.2.0+ent: method "tpm" is registered on `vault agent`, not
# `vault proxy`. Each unit runs agent with tpm_cert + auto_auth method tpm,
# fixed to one role, and forces that token on the unix listener.
set -euo pipefail
STAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${STAGE_DIR}/common.sh"

device="${1:-node01}"
domain="${2:-devices.lab.local}"
DEVICE_CN="${device}.${domain}"
APPS=(payments analytics)
RUN_DIR="/run/vault-proxy"
CONF_DIR="/etc/vault-proxy"
STATE_ROOT="/var/lib/vault-agent"
UNIT_PATH="/etc/systemd/system/vault-proxy@.service"
CA_PEM="${LAB_TLS_DIR}/vault-ca.pem"
VAULT_BIN="/usr/local/bin/vault"

require_cmd vault jq systemctl install useradd id stat || die "missing prerequisites"
[[ -x "${VAULT_BIN}" ]] || die "Vault binary missing at ${VAULT_BIN} — run 'task provision'"
[[ -f "${CA_PEM}" ]] || die "no Vault CA at ${CA_PEM} — run 'task vault' first"
[[ -S "${SWTPM_UNIX_SOCK}" ]] || die "no ${SWTPM_UNIX_SOCK} — run 'task tpm' first"

log_step "Workflow 3: isolated per-application Vault proxies"

systemctl stop vault-proxy-single vault-proxy@payments vault-proxy@analytics \
  >/dev/null 2>&1 || true
if pgrep -f 'vault (agent|proxy) -config=/etc/vault-proxy/' >/dev/null 2>&1; then
  log_detected "a vault agent/proxy outside systemd" "stopping it"
  pkill -f 'vault (agent|proxy) -config=/etc/vault-proxy/' || true
  sleep 0.3
fi

install -d -m 0755 "${RUN_DIR}" "${CONF_DIR}" "${STATE_ROOT}"

for app in "${APPS[@]}"; do
  home="/var/lib/lab-${app}"
  if ! id "${app}" >/dev/null 2>&1; then
    useradd --system --create-home --home-dir "${home}" --shell /usr/sbin/nologin "${app}"
    log_ok "created user ${app}"
  else
    log_detected "user ${app}" "leaving the account in place"
  fi
  install -d -o "${app}" -g "${app}" -m 0700 "${home}"
  install -d -m 0700 "${STATE_ROOT}/${app}/tpm"
done

# Confirm the TPM roles exist before starting agents that need them.
for app in "${APPS[@]}"; do
  if ! as_lab_user_allow_fail vault read "auth/tpm/role/${app}-app" >/dev/null 2>&1; then
    die "auth/tpm/role/${app}-app missing — run 'task config' first"
  fi
done

for app in "${APPS[@]}"; do
  # Authoritative copy of templates/vault-proxy.hcl.tpl.
  if write_if_changed "${CONF_DIR}/${app}.hcl" <<EOF
# Generated by scripts/81_app_proxies.sh.
# Role ${app}-app, user ${app}. TPM auto-auth via vault agent.
vault {
  address = "https://127.0.0.1:8200"
  ca_cert = "${CA_PEM}"
}

tpm_cert "host_identity" {
  mount_path = "auth/tpm"
  role_name  = "${app}-app"

  tpm {
    device_path = "${SWTPM_UNIX_SOCK}"
  }

  renew {
    percent_renew_before_expiry = 20
    min_backoff                 = "5s"
    max_backoff                 = "5m"
  }

  csr {
    CN = "${DEVICE_CN}"
  }

  destination {
    path  = "${STATE_ROOT}/${app}/tpm"
    umask = "077"
  }
}

auto_auth {
  method "tpm" {
    mount_path = "auth/tpm"
    config = {
      tpm_cert  = "host_identity"
      role_name = "${app}-app"
    }
  }
}

api_proxy {
  use_auto_auth_token = "force"
}

listener "unix" {
  address      = "${RUN_DIR}/${app}.sock"
  socket_mode  = "600"
  socket_user  = "${app}"
  socket_group = "${app}"
  tls_disable  = true
}
EOF
  then
    log_info "Wrote ${CONF_DIR}/${app}.hcl"
  else
    log_detected "unchanged ${CONF_DIR}/${app}.hcl" "leaving it"
  fi
done

unit_changed=0
# Authoritative copy of templates/vault-proxy.service.tpl.
if write_if_changed "${UNIT_PATH}" <<'EOF'
# Generated by scripts/81_app_proxies.sh.
[Unit]
Description=Vault agent API proxy for %i (TPM auto-auth)
After=network-online.target vault-dev.service swtpm-unix-bridge.service
Wants=vault-dev.service swtpm-unix-bridge.service

[Service]
Type=simple
ExecStart=/usr/local/bin/vault agent -config=/etc/vault-proxy/%i.hcl
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
then
  unit_changed=1
  log_info "Wrote ${UNIT_PATH}"
fi

if (( unit_changed == 1 )); then
  systemctl daemon-reload
fi

wait_for_app_socket() {
  local app="$1" sock="${RUN_DIR}/${1}.sock" unit="vault-proxy@${1}" mode owner recent
  # Up to ~90s: attestation retry backoff after a rate-limit is ~50s.
  for _ in $(seq 1 360); do
    if systemctl is-failed --quiet "${unit}"; then
      break
    fi
    # Only the newest journal lines — older failed attempts from a prior
    # restart must not abort a run that later succeeds.
    recent="$(journalctl -u "${unit}" -n 30 --no-pager 2>/dev/null || true)"
    if [[ -S "${sock}" ]]; then
      mode="$(stat -c '%a' "${sock}")"
      owner="$(stat -c '%U:%G' "${sock}")"
      if [[ "${mode}" == "600" && "${owner}" == "${app}:${app}" ]] \
        && printf '%s' "${recent}" | grep -q 'authentication successful'; then
        log_ok "${sock} owned by ${owner}, mode ${mode} (TPM auth ok)"
        return 0
      fi
    fi
    sleep 0.25
  done
  log_error "journal follows"
  journalctl -u "${unit}" --no-pager -n 50 >&2 || true
  die "${sock} did not come up with TPM authentication"
}

# One agent at a time. Concurrent attestation exhausts swtpm's transient object
# slots ("out of memory for object contexts"). Restart the device TPM first so
# leftover openssl / earlier-agent contexts are gone.
log_info "Restarting swtpm@device to clear transient TPM contexts"
systemctl restart swtpm@device
wait_for_unit swtpm@device 30 || die "swtpm@device did not recover"
systemctl restart swtpm-unix-bridge
wait_for_unit swtpm-unix-bridge 15 || die "swtpm-unix-bridge did not recover"
sleep 0.5

# Failed agent logins trip the TPM dictionary-attack lockout (default max
# auth fail is 3). Clear it and raise the threshold so a flaky attestation
# retry does not brick the rest of the demo.
log_info "Clearing TPM dictionary-attack lockout"
as_lab_user tpm2_dictionarylockout -c || true
as_lab_user tpm2_dictionarylockout -s -n 32 -t 60 -l 60 \
  || log_warn "could not soften TPM DA parameters — continuing with defaults"

# Stale destination blobs from a prior failed run make the agent try Load()
# against a wiped TPM and burn auth fails into DA lockout again.
for app in "${APPS[@]}"; do
  find "${STATE_ROOT}/${app}/tpm" -mindepth 1 -type f -delete 2>/dev/null || true
done

first=1
for app in "${APPS[@]}"; do
  if (( first == 0 )); then
    # auth/tpm rate-limits gentpmcert/begin per EK. Two roles on one TPM need
    # a gap between attestations or the second begin fails with
    # "rate limit exceeded for this EK".
    log_info "Waiting 60s for the TPM auth EK rate limit before the next attestation"
    sleep 60
  fi
  first=0
  log_info "Starting vault-proxy@${app} (TPM attest + login as ${app}-app)"
  systemctl enable "vault-proxy@${app}" >/dev/null
  systemctl restart "vault-proxy@${app}"
  wait_for_app_socket "${app}"
done

log_info ""
log_ok "each application reaches Vault only through its TPM-authenticated agent socket"
log_info "Next: task demo:multi-app"
